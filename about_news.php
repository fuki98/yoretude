<br>August 14, 2005

<br><br>An anonymous reader writes "A new folksonomy website that seems to be catching on is YouTube, a service similar to Flickr, except that it is for sharing and hosting short video clips instead of photos.
Like Flickr, its core functionality is implemented in Flash.
Videos can be tagged, searched, discussed, etc through a social network.
YouTube has developer APIs, RSS feeds, and the ability to embed videos directly into other web pages.
The website was recently profiled on TechCrunch as an up-and-coming Web 2.0 application."

<br><br><br><span class="highlight"><a href="http://web.archive.org/web/20050924023654/http://www.techcrunch.com/?p=137" target="_blank">TechCrunch Profile</a></span>
<br>August 8, 2005

<br><br>YoreTude is very much like flickr, but for videos. You can upload videos in a number of different formats ( .AVI, .MOV, and .MPG ). Videos can be of any length, but must be less than 100 mb in total size. Editorial restrictions consist of no nudity and your video must be appropriate for all audiences. For additional requirements, see their help page.
The service is completely free to users (publishers and viewers). YoreTude converts video to a flash format, and therefore upload and playback is extremely fast. In our tests, videos uploaded significantly faster than in other services.

<br><br>YoreTude is also a sharing network. You can add friends who are also member of the network, and email any video to anyone. YoreTude also provides easy to use copy/paste code for emailing and posting on a website. You can also tag your videos, which results in bunching in a very similar way as flickr. Overall, the service is excellent.

<br><br>The service has recently been launched but seems to have quite a few users who have posted lots of content. Our absolute favorite is Matt Dances around the World. It shows an ex-programmer who's travelling the world and dancing at famous locations - it's awesome and very popular on the site. Other favorites are this and this (that's me in the red shirt. ok, not) (how do people do this?).

<br><br>I suspect YoreTude will be quickly acquired and/or duplicated. We love it.


